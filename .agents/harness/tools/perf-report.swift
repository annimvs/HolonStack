// perf-report.swift — writes records/PERF.md: the project's cost scoreboard, from FINDINGS/, the catalog and the last scan (rules/PERF.md).
// Usage: perf-report   Prints the path it wrote. Exit 0.
import Foundation

// MARK: - Reading records

// MARK: - Finding
/// The fields of one filed finding that the report counts and lists.
struct Finding {
    let name: String
    let unit: String
    let declared: String
    let necessary: String
    let status: String
    let priority: String
    let worth: String
    let hasFix: Bool
}

/// Takes a field name and a record's text; returns the quoted value of the first `  name: "…"` line, or nil.
func fieldValue(_ key: String, in text: String) -> String? {
    for line in text.components(separatedBy: "\n") {
        let t = line.trimmingCharacters(in: .whitespaces)
        guard t.hasPrefix(key + ": \""), t.hasSuffix("\""), t.count > key.count + 3 else { continue }
        return String(t.dropFirst(key.count + 3).dropLast())
    }
    return nil
}

/// Takes a field name and a record's text; returns the unquoted value (an atom or an id) of the first `  name: value` line, or nil.
func atomValue(_ key: String, in text: String) -> String? {
    for line in text.components(separatedBy: "\n") {
        let t = line.trimmingCharacters(in: .whitespaces)
        if t.hasPrefix(key + ": "), !t.hasPrefix(key + ": \"") { return String(t.dropFirst(key.count + 2)) }
    }
    return nil
}

/// Lists the files in a folder whose names fit a prefix and the .closure suffix. Takes the folder and the prefix; returns full paths, sorted.
func closureFiles(_ dir: String, prefix: String) -> [String] {
    // a missing folder just means nothing has been filed there yet
    let names = (try? FileManager.default.contentsOfDirectory(atPath: dir)) ?? []
    return names.filter { $0.hasPrefix(prefix) && $0.hasSuffix(".closure") }.sorted().map { dir + "/" + $0 }
}

/// Reads every finding record under the project. Takes the project path; returns the findings in file order.
func loadFindings(_ proj: String) -> [Finding] {
    var found: [Finding] = []
    for path in closureFiles(proj + "/.agents/records/FINDINGS", prefix: "finding-") {
        guard let t = try? String(contentsOfFile: path, encoding: .utf8) else { continue }
        found.append(
            Finding(
                name: fieldValue("name", in: t) ?? path, unit: fieldValue("unit", in: t) ?? "",
                declared: fieldValue("declared", in: t) ?? "", necessary: fieldValue("necessary", in: t) ?? "",
                status: atomValue("status", in: t) ?? "open", priority: atomValue("priority", in: t) ?? "none",
                worth: atomValue("worth", in: t) ?? "meaningful", hasFix: atomValue("fix", in: t) != nil))
    }
    return found
}

// MARK: - Rendering

/// Builds the PERF.md text. Takes the findings, the catalog counts (entries, entries with detect) and the last scan summary line.
func render(_ f: [Finding], catalog: (Int, Int), scan: String) -> String {
    /// Counts the findings that have one status.
    func count(_ status: String) -> Int { f.filter { $0.status == status }.count }
    let waste = f.filter { $0.worth == "waste" || $0.worth == "vestigial" }
    let withFix = f.filter { $0.hasFix }.count
    var out = [
        "# Performance", "",
        "Generated by `perf-report`; do not edit. Scan with `.agents/harness/bin/perf-scan`, file findings, "
            + "then run `.agents/harness/bin/perf-confirm`.", "",
        "## Scoreboard", "", "| Measure | Value |", "|---|---|",
        "| Findings filed | \(f.count) |",
        "| Open, check not passed | \(count("open")) |",
        "| Confirmed, not yet fixed | \(count("confirmed")) |",
        "| Fixed | \(count("fixed")) |",
        "| Won't fix | \(count("wontfix")) |",
        "| Waste or vestigial | \(waste.count) |",
        "| With a catalog fix | \(withFix) of \(f.count) |",
        "| Catalog entries the scanner can match | \(catalog.1) of \(catalog.0) |",
        "| Last scan | \(scan) |", "",
        "## Confirmed gaps, highest priority first", "",
    ]
    let order = ["high", "medium", "low", "none"]
    let confirmed = f.filter { $0.status == "confirmed" }.sorted {
        (order.firstIndex(of: $0.priority) ?? 9) < (order.firstIndex(of: $1.priority) ?? 9)
    }
    if confirmed.isEmpty { out.append("None.") }
    for c in confirmed { out.append("- \(c.priority): \(c.name), \(c.unit): \(c.declared), needs \(c.necessary)") }
    return out.joined(separator: "\n") + "\n"
}

// MARK: - Driver

let proj = ProcessInfo.processInfo.environment["CLAUDE_PROJECT_DIR"] ?? FileManager.default.currentDirectoryPath
let entries = closureFiles(proj + "/.agents/records/CATALOG", prefix: "entry-")
let withDetect = entries.filter { path in
    guard let t = try? String(contentsOfFile: path, encoding: .utf8) else { return false }
    return fieldValue("detect", in: t) != nil
}
let summary = (try? String(contentsOfFile: proj + "/.agents/harness/.cache/perf-scan.summary", encoding: .utf8))?
    .trimmingCharacters(in: .whitespacesAndNewlines)
let text = render(loadFindings(proj), catalog: (entries.count, withDetect.count), scan: summary ?? "no scan yet")
let target = proj + "/.agents/records/PERF.md"
do {
    try text.write(toFile: target, atomically: true, encoding: .utf8)
    print("perf-report: wrote \(target)")
} catch {
    print("perf-report: could not write \(target): \(error)")
    exit(1)
}
exit(0)
